"""Audit the frozen OULAD Experiment 3 identity boundary and summarize results.

This is read-only with respect to private inputs. Published outputs contain only
aggregate counts, statistics and file hashes; no learner identifiers are emitted.

Example:
  python audit_and_summarize.py --oulad-zip /data/oulad.zip \
    --experiment-root /work/oulad_experiment \
    --experiment3-results /results/oulad_experiment3 --output ./audit

The experiment root must contain data/features.csv.gz, protocol.json,
results_verified/{J,B}/split_seed*.json and *_base.{npz,json}, plus
experiment3_work/*.parquet, generated by the frozen analysis pipeline.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import zipfile
from pathlib import Path

import numpy as np
import pandas as pd

KEY = ["code_module", "code_presentation", "id_student", "t"]
CELL = ["season", "course", "day", "base"]
GAINS = ["G_S_Platt", "G_T_Platt", "G_T_star_Platt", "A_Platt",
         "G_T_star_intercept", "target_slope_increment"]


def sha(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def ids(frame):
    return set(frame.id_student.astype(int))


def macro_bootstrap(frame, field, cluster="course", repetitions=10000):
    """Equal-pair mean; resample whole module clusters, retaining their rows."""
    grouped = frame.groupby(cluster)[field].agg(["sum", "count"])
    sums, counts = grouped["sum"].to_numpy(), grouped["count"].to_numpy()
    rng = np.random.default_rng(20261002)
    take = rng.integers(0, len(grouped), size=(repetitions, len(grouped)))
    boot = sums[take].sum(axis=1) / counts[take].sum(axis=1)
    return np.quantile(boot, [.025, .975]).tolist()


def summarize(results, output):
    rows = pd.read_csv(results / "decomposition_by_seed.csv")
    assert len(rows) == 360
    assert rows.groupby(CELL).size().eq(5).all()
    assert np.allclose(rows.A_Platt, rows.G_T_star_Platt - rows.G_T_Platt)
    cols = GAINS + ["source_cal_n", "target_n", "source_raw_Brier", "target_raw_Brier"]
    cell = rows.groupby(CELL, as_index=False)[cols].mean()
    assert len(cell) == 72
    cell["target_historical_Brier"] = cell.target_raw_Brier - cell.G_T_Platt
    cell["target_adapted_Brier"] = cell.target_raw_Brier - cell.G_T_star_Platt
    cell.to_csv(output / "oulad_course_landmark_model.csv", index=False)
    summary = []
    for keys, group in cell.groupby(["season", "day", "base"]):
        record = dict(zip(["season", "day", "base"], keys))
        record.update(pairs=len(group), seeds_per_pair=5,
                      target_enrollments=int(group.target_n.sum()),
                      positive_G_T_pairs=int(group.G_T_Platt.gt(0).sum()),
                      positive_A_pairs=int(group.A_Platt.gt(0).sum()))
        for col in GAINS + ["target_raw_Brier", "target_historical_Brier", "target_adapted_Brier"]:
            record[col] = float(group[col].mean())
        for col in ["G_T_Platt", "A_Platt"]:
            record[col + "_min"] = float(group[col].min())
            record[col + "_max"] = float(group[col].max())
        summary.append(record)
    pd.DataFrame(summary).to_csv(output / "oulad_season_landmark_model.csv", index=False)
    # Across seasons, BBB/DDD/FFF recur. Resample module clusters, not nine
    # nominal presentation pairs as independent units; seeds are averaged first.
    model_day = []
    for keys, group in cell.groupby(["day", "base"]):
        record = dict(zip(["day", "base"], keys))
        record.update(pairs=len(group), module_clusters=int(group.course.nunique()))
        for col in GAINS:
            record[col] = float(group[col].mean())
            record[col + "_lo"], record[col + "_hi"] = macro_bootstrap(group, col)
        model_day.append(record)
    pd.DataFrame(model_day).to_csv(output / "oulad_landmark_model_intervals.csv", index=False)
    return {col: float(cell[col].mean()) for col in GAINS}


def run(args):
    root, results, out = args.experiment_root, args.experiment3_results, args.output
    out.mkdir(parents=True, exist_ok=True)
    protocol = json.loads((root / "protocol.json").read_text(encoding="utf-8"))
    data = pd.read_csv(root / "data/features.csv.gz")
    with zipfile.ZipFile(args.oulad_zip) as archive:
        info = pd.read_csv(archive.open("studentInfo.csv"), usecols=KEY[:3])
    exploration_ids = set(json.loads((root / "results_verified/J/exploration_ids.json").read_text()))
    sourcezip_hash = sha(args.oulad_zip)
    expected_hash = json.loads((root / "data/data_audit.json").read_text(encoding="utf-8"))["source_sha256"]
    assert sourcezip_hash == expected_hash, "The raw input is not the frozen OULAD archive."
    audit, roles_audit, folds_audit, hashes = [], [], [], []
    for season in ["J", "B"]:
        spec = protocol["exploration" if season == "J" else "confirmation"]
        source = data[data.code_presentation.eq(spec["source"]) & data.code_module.isin(spec["modules"])]
        candidate = data[data.code_presentation.eq(spec["target"]) & data.code_module.isin(spec["modules"])]
        # This intentionally has no code_module filter, matching the real code.
        source_full_ids = ids(info[info.code_presentation.eq(spec["source"])])
        target = candidate[~candidate.id_student.isin(source_full_ids)]
        after_source = len(target)
        if season == "B":
            target = target[~target.id_student.isin(exploration_ids)]
        else:
            assert exploration_ids == ids(source) | ids(target)
        for day in protocol["times"]:
            src = source[source.t.eq(day)]
            tgt = target[target.t.eq(day)].reset_index(drop=True)
            for seed in protocol["seeds"]:
                splitpath = root / "results_verified" / season / f"split_seed{seed}.json"
                split = json.loads(splitpath.read_text())
                role_frames = {r: src[src.id_student.isin(split[k])].reset_index(drop=True)
                               for r, k in [("training", "train"), ("validation", "base_validation"),
                                            ("calibration", "calibration_order")]}
                role_ids = {r: ids(frame) for r, frame in role_frames.items()}
                assert ids(src) == set.union(*role_ids.values())
                assert not role_ids["training"] & role_ids["validation"]
                assert not role_ids["training"] & role_ids["calibration"]
                assert not role_ids["validation"] & role_ids["calibration"]
                for base in protocol["base_models"]:
                    stem = f"{base}_s{seed}_t{day}"
                    cachepath = root / "results_verified" / season / (stem + "_base.npz")
                    metapath = cachepath.with_suffix(".json")
                    predpath = root / "experiment3_work" / f"{season}_{stem}.parquet"
                    metadata = json.loads(metapath.read_text())
                    pred = pd.read_parquet(predpath)
                    sp = pred[pred.population.eq("source_calibration")].reset_index(drop=True)
                    tp = pred[pred.population.eq("target")].reset_index(drop=True)
                    with np.load(cachepath) as cache:
                        assert np.array_equal(cache["cal_keys"], role_frames["calibration"][KEY].astype(str).to_numpy())
                        assert np.array_equal(cache["test_keys"], tgt[KEY].astype(str).to_numpy())
                        assert np.array_equal(cache["cal_keys"], sp[KEY].astype(str).to_numpy())
                        assert np.array_equal(cache["test_keys"], tp[KEY].astype(str).to_numpy())
                        assert np.array_equal(cache["pc"], sp.raw.to_numpy())
                        assert np.array_equal(cache["pt"], tp.raw.to_numpy())
                    for role, metakey in [("training", "n_train"), ("validation", "n_validation"), ("calibration", "n_calibration")]:
                        assert metadata[metakey] == len(role_frames[role])
                    assert metadata["n_test"] == len(tgt)
                    assert np.array_equal(sp.y, role_frames["calibration"].y)
                    assert np.array_equal(tp.y, tgt.y)
                    rec = dict(season=season, day=day, seed=seed, base=base,
                               source_presentation=spec["source"], target_presentation=spec["target"],
                               source_all_modules_ids=len(source_full_ids), source_used_ids=len(ids(src)),
                               source_used_rows=len(src), target_unique_ids=len(ids(tgt)), target_rows=len(tgt),
                               target_vs_full_source_overlap=len(ids(tgt) & source_full_ids),
                               target_vs_training_overlap=len(ids(tgt) & role_ids["training"]),
                               target_vs_validation_overlap=len(ids(tgt) & role_ids["validation"]),
                               target_vs_calibration_overlap=len(ids(tgt) & role_ids["calibration"]),
                               target_vs_source_union_overlap=len(ids(tgt) & set.union(*role_ids.values())),
                               target_vs_J_exploration_overlap=(len(ids(tgt) & exploration_ids) if season == "B" else 0),
                               exact_cache_and_prediction_keys=True, exact_cache_probabilities=True)
                    assert not any(v for k, v in rec.items() if k.endswith("_overlap"))
                    audit.append(rec)
                    for role, frame in role_frames.items():
                        roles_audit.append(dict(season=season, day=day, seed=seed, base=base, role=role,
                                                rows=len(frame), unique_ids=len(ids(frame)),
                                                n_courses=int(frame.code_module.nunique())))
                    for population, frame in [("source_calibration", sp), ("target", tp)]:
                        assert set(frame.fold) == set(range(5))
                        assert frame.groupby("id_student").fold.nunique().eq(1).all()
                        for fold in range(5):
                            trainids = ids(frame[frame.fold.ne(fold)])
                            testids = ids(frame[frame.fold.eq(fold)])
                            overlap = len(trainids & testids)
                            assert overlap == 0
                            folds_audit.append(dict(season=season, day=day, seed=seed, base=base,
                                                    population=population, fold=fold,
                                                    fit_unique_ids=len(trainids), score_unique_ids=len(testids),
                                                    overlap=overlap))
                    hashes.extend([dict(file=str(p.relative_to(root)), sha256=sha(p))
                                   for p in [splitpath, cachepath, metapath, predpath]])
    assert len(audit) == 80 and len(folds_audit) == 800
    audit = pd.DataFrame(audit)
    audit.to_csv(out / "oulad_identity_by_job.csv", index=False)
    pd.DataFrame(roles_audit).to_csv(out / "oulad_fitting_roles.csv", index=False)
    pd.DataFrame(folds_audit).to_csv(out / "oulad_oof_identity_audit.csv", index=False)
    pd.DataFrame(hashes).drop_duplicates().to_csv(out / "oulad_input_hashes.csv", index=False)
    statistics = summarize(results, out)
    summary = dict(status="PASS", model_jobs=80, pair_model_landmark_seed_cells=360,
                   distinct_pair_model_landmark_cells=72, crossfit_checks=800,
                   all_target_source_role_intersections_zero=True,
                   all_source_role_intersections_zero=True,
                   all_crossfit_learner_intersections_zero=True,
                   source_exclusion_scope="All course modules in the full source presentation in studentInfo.csv, including learners outside the eligible landmark risk sets.",
                   confirmation_extra_exclusion="2014B target excludes all retained 2013J/2014J exploration learner IDs.",
                   raw_archive_sha256=sourcezip_hash,
                   decomposition_sha256=sha(results / "decomposition_by_seed.csv"),
                   audit_script_sha256=sha(__file__),
                   overall_seed_then_pair_cell_means=statistics,
                   source_all_modules_unique_ids=audit.groupby("season").source_all_modules_ids.first().astype(int).to_dict(),
                   target_unique_ids_by_season_day=audit.groupby(["season", "day"]).target_unique_ids.first().astype(int).reset_index().to_dict("records"),
                   no_refit_required="The questioned identity intersections are already zero under the actual frozen pipeline; original estimates are retained.",
                   inference="Summaries average five seeds per course-pair cell, then weight pairs equally. Across-season intervals resample six code_module clusters (10,000 draws), not seeds; limited clusters make them exploratory.")
    (out / "oulad_identity_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--oulad-zip", type=Path, required=True)
    parser.add_argument("--experiment-root", type=Path, required=True)
    parser.add_argument("--experiment3-results", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    run(parser.parse_args())
